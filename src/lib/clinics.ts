import { getAppDatabase } from "@/lib/app-database";

export type Clinic = {
  id: number;
  name: string;
  address: string;
};

type ClinicRow = {
  ID: number;
  ClinicName: string;
  Address: string;
};

let ensurePromise: Promise<void> | null = null;

export function ensureClinics(): Promise<void> {
  if (!ensurePromise) {
    ensurePromise = createClinicTable().catch((error: unknown) => {
      ensurePromise = null;
      throw error;
    });
  }
  return ensurePromise;
}

async function createClinicTable() {
  const db = await getAppDatabase();
  await db.exec(`
    CREATE TABLE IF NOT EXISTS "clinic" (
      "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "ClinicName" text NOT NULL,
      "Address" text NOT NULL
    )
  `);
}

export async function listClinics(): Promise<Clinic[]> {
  await ensureClinics();
  const db = await getAppDatabase();
  const rows = await db.all<ClinicRow>(`
    SELECT "ID", "ClinicName", "Address"
    FROM "clinic"
    ORDER BY "ID" ASC
  `);

  return rows.map((row) => ({
    id: Number(row.ID),
    name: row.ClinicName,
    address: row.Address,
  }));
}

export async function insertClinic(name: string, address: string): Promise<void> {
  await ensureClinics();
  const db = await getAppDatabase();
  await db.run(`INSERT INTO "clinic" ("ClinicName", "Address") VALUES (?, ?)`, [name, address]);
}

/** Returns false when no clinic has this id. */
export async function updateClinic(id: number, name: string, address: string): Promise<boolean> {
  await ensureClinics();
  const db = await getAppDatabase();
  const result = await db.run(
    `UPDATE "clinic" SET "ClinicName" = ?, "Address" = ? WHERE "ID" = ?`,
    [name, address, id],
  );
  return result.changes > 0;
}
