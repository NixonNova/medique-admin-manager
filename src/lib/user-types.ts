import { getAppDatabase } from "@/lib/app-database";

export type UserTypeOption = {
  id: number;
  name: string;
};

const SEEDED_USER_TYPES = ["Staff Admin", "Doctor"] as const;

let ensurePromise: Promise<void> | null = null;

type UserTypeRow = {
  ID: number;
  Name: string;
};

export function ensureUserTypes(): Promise<void> {
  if (!ensurePromise) {
    ensurePromise = createUserTypeTables().catch((error: unknown) => {
      ensurePromise = null;
      throw error;
    });
  }
  return ensurePromise;
}

async function createUserTypeTables() {
  const db = await getAppDatabase();

  await db.exec(`
    CREATE TABLE IF NOT EXISTS "usertype" (
      "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "Name" text NOT NULL UNIQUE
    )
  `);

  await db.exec(`
    CREATE TABLE IF NOT EXISTS "userusertype" (
      "ID" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "UserID" text NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
      "UserTypeID" integer NOT NULL REFERENCES "usertype" ("ID") ON DELETE CASCADE,
      UNIQUE ("UserID", "UserTypeID")
    )
  `);

  for (const name of SEEDED_USER_TYPES) {
    await db.run(
      `INSERT INTO "usertype" ("Name") VALUES (?) ON CONFLICT ("Name") DO NOTHING`,
      [name],
    );
  }
}

export async function listUserTypes(): Promise<UserTypeOption[]> {
  await ensureUserTypes();
  const db = await getAppDatabase();
  const rows = await db.all<UserTypeRow>(`
    SELECT "ID", "Name"
    FROM "usertype"
    ORDER BY "ID" ASC
  `);

  return rows.map((row) => ({
    id: Number(row.ID),
    name: row.Name,
  }));
}

export function normalizeUserTypeIds(value: unknown): number[] | null {
  if (value == null) {
    return [];
  }
  if (!Array.isArray(value)) {
    return null;
  }

  const ids = value.map((item) => (typeof item === "number" ? item : Number.NaN));
  if (ids.some((id) => !Number.isInteger(id) || id < 1)) {
    return null;
  }

  return [...new Set(ids)];
}

/** Returns an error when any id is missing from the lookup table. */
export async function userTypeSelectionError(ids: number[]): Promise<string | null> {
  await ensureUserTypes();
  if (ids.length === 0) {
    return null;
  }

  const db = await getAppDatabase();
  const placeholders = ids.map(() => "?").join(", ");
  const rows = await db.all<{ ID: number }>(
    `SELECT "ID" FROM "usertype" WHERE "ID" IN (${placeholders})`,
    ids,
  );
  const found = new Set(rows.map((row) => Number(row.ID)));
  if (ids.some((id) => !found.has(id))) {
    return "Select a valid user type.";
  }

  return null;
}

async function insertUserTypeAssignments(
  db: Awaited<ReturnType<typeof getAppDatabase>>,
  userId: string,
  userTypeIds: number[],
) {
  for (const userTypeId of userTypeIds) {
    await db.run(
      `
        INSERT INTO "userusertype" ("UserID", "UserTypeID")
        VALUES (?, ?)
        ON CONFLICT ("UserID", "UserTypeID") DO NOTHING
      `,
      [userId, userTypeId],
    );
  }
}

export async function saveUserTypeAssignments(userId: string, userTypeIds: number[]) {
  if (userTypeIds.length === 0) {
    return;
  }

  const db = await getAppDatabase();
  await insertUserTypeAssignments(db, userId, userTypeIds);
}

/** Replaces the user's assigned types, including clearing them when none are selected. */
export async function replaceUserTypeAssignments(userId: string, userTypeIds: number[]) {
  await ensureUserTypes();
  const db = await getAppDatabase();
  await db.transaction(async (tx) => {
    if (userTypeIds.length === 0) {
      await tx.run(`DELETE FROM "userusertype" WHERE "UserID" = ?`, [userId]);
      return;
    }

    const placeholders = userTypeIds.map(() => "?").join(", ");
    await tx.run(
      `DELETE FROM "userusertype" WHERE "UserID" = ? AND "UserTypeID" NOT IN (${placeholders})`,
      [userId, ...userTypeIds],
    );
    await insertUserTypeAssignments(tx, userId, userTypeIds);
  });
}
